// Embeds the guide's Markdown in the server bundle (doc 19 §4). The installer ships Next's
// standalone output, which does not carry files read from disk at runtime, so the content has to
// be code. Runs before dev, build, test and typecheck (apps/web/package.json).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contentDir = path.join(root, 'content', 'rehber');
const outFile = path.join(root, 'src', 'lib', 'guide', 'generated.ts');

const files = readdirSync(contentDir)
  .filter((f) => f.endsWith('.md'))
  .sort();
const entries = files.map((file) => ({ file, source: readFileSync(path.join(contentDir, file), 'utf8') }));

const out =
  '// Generated by scripts/generate-guide.mjs from content/rehber/ — do not edit (doc 19 §4).\n' +
  `export const RAW_TOPICS: readonly { file: string; source: string }[] = ${JSON.stringify(entries, null, 2)};\n`;

writeFileSync(outFile, out);

// The header's "?" link runs in the browser on every screen. It needs only each topic's id and
// routes, not the whole guide, so those go in a module of their own. Read with a deliberately
// small pattern; route-match.test.ts proves it agrees with the real parser.
const routeIndex = entries
  .map(({ source }) => {
    const head = /^---\r?\n([\s\S]*?)\r?\n---/.exec(source)?.[1] ?? '';
    const id = /^id:\s*(\S+)/m.exec(head)?.[1] ?? '';
    const routes = [...head.matchAll(/^\s+-\s+(\/\S*)/gm)].map((m) => m[1]);
    return { id, routes };
  })
  .filter((t) => t.routes.length > 0);
writeFileSync(
  path.join(root, 'src', 'lib', 'guide', 'generated-routes.ts'),
  '// Generated by scripts/generate-guide.mjs from content/rehber/ — do not edit (doc 19 §6).\n' +
    `export const GUIDE_ROUTE_INDEX: readonly { id: string; routes: readonly string[] }[] = ${JSON.stringify(routeIndex, null, 2)};\n`,
);
console.log(`guide: ${entries.length} topics embedded`);
